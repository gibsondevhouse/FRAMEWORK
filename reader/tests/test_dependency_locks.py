"""Dependencies and CI (register SEC-005): the Python locks are fully pinned and hashed and
agree with the ranges they were compiled from, the audit covers every pin, and the workflows
pin their actions by commit and run with least privilege."""
import importlib.util
import re
import unittest
from pathlib import Path

import yaml
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

from tests.base import HermeticTestCase

REPO = Path(__file__).resolve().parents[2]
READER = REPO / "reader"
WORKFLOWS = REPO / ".github" / "workflows"
LOCKS = ("requirements", "requirements-dev", "requirements-audit")

_spec = importlib.util.spec_from_file_location("audit_python_locks", REPO / ".github" / "scripts" / "audit_python_locks.py")
audit = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(audit)


def lock_text(name: str) -> str:
    return (READER / f"{name}.txt").read_text(encoding="utf-8")


def pins(name: str, here_only: bool = False) -> list[Requirement]:
    """The pinned requirements of a lock; with `here_only`, those that apply to this interpreter."""
    out = []
    for block in audit.requirement_blocks(lock_text(name)):
        req = Requirement(block[0].rstrip("\\").strip())
        if not here_only or req.marker is None or req.marker.evaluate():
            out.append(req)
    return out


def ranges(name: str) -> list[Requirement]:
    """The requirements a `.in` file asks for (not its `-r` / `-c` lines)."""
    lines = (READER / f"{name}.in").read_text(encoding="utf-8").splitlines()
    return [Requirement(l) for l in (x.split("#")[0].strip() for x in lines) if l and not l.startswith("-")]


class LockFileTests(HermeticTestCase):
    def test_every_requirement_is_pinned_and_hashed(self):
        for name in LOCKS:
            blocks = audit.requirement_blocks(lock_text(name))       # raises on anything that is not a pin
            self.assertGreater(len(blocks), 5, name)
            for block in blocks:
                req = Requirement(block[0].rstrip("\\").strip())
                self.assertEqual([s.operator for s in req.specifier], ["=="], block[0])
                hashes = [l for l in block[1:] if "--hash=sha256:" in l]
                self.assertTrue(hashes, f"{name}: {req.name} has no hash")
                for line in hashes:
                    self.assertRegex(line.strip().rstrip("\\").strip(), r"^--hash=sha256:[0-9a-f]{64}$")

    def test_each_lock_satisfies_the_ranges_it_was_compiled_from(self):
        """Editing a .in file without recompiling its lock fails here."""
        for name in LOCKS:
            locked = {canonicalize_name(p.name): p for p in pins(name, here_only=True)}
            wanted = ranges(name) + (ranges("requirements") if name == "requirements-dev" else [])
            self.assertTrue(wanted, name)
            for want in wanted:
                pin = locked.get(canonicalize_name(want.name))
                self.assertIsNotNone(pin, f"{name}.txt has no pin for {want.name}; recompile the lock")
                version = str(next(iter(pin.specifier)).version)
                self.assertTrue(want.specifier.contains(version, prereleases=True),
                                f"{name}.txt pins {want.name}=={version}, outside {want.specifier}; recompile the lock")

    def test_the_dev_lock_tests_what_the_runtime_lock_ships(self):
        dev = {canonicalize_name(p.name): str(p.specifier) for p in pins("requirements-dev", here_only=True)}
        for pin in pins("requirements", here_only=True):
            self.assertEqual(dev.get(canonicalize_name(pin.name)), str(pin.specifier), pin.name)

    def test_the_locks_record_how_to_rebuild_them_and_nothing_about_this_machine(self):
        for name in LOCKS:
            head = lock_text(name).splitlines()[:2]
            self.assertIn("autogenerated by uv", head[0])
            self.assertIn(f"uv pip compile {name}.in --universal --generate-hashes", head[1])
            self.assertIn(f"--output-file {name}.txt", head[1])
            self.assertNotRegex(lock_text(name), r"/Users/|/home/|[A-Za-z]:\\\\")


class AuditCoverageTests(HermeticTestCase):
    SAMPLE = (
        "# a comment\n"
        "fastapi==0.1 ; python_full_version < '3.11' \\\n    --hash=sha256:" + "a" * 64 + "\n"
        "fastapi==0.2 ; python_full_version >= '3.11' \\\n    --hash=sha256:" + "b" * 64 + " \\\n    --hash=sha256:" + "c" * 64 + "\n"
        "    # via -r requirements.in\n"
        "colorama==0.4.6 ; sys_platform == 'win32' \\\n    --hash=sha256:" + "d" * 64 + "\n"
        "Typing_Extensions==4.0 \\\n    --hash=sha256:" + "e" * 64 + "\n"
    )

    def test_pins_for_other_platforms_and_versions_are_all_audited(self):
        groups = audit.audit_groups(self.SAMPLE)
        self.assertEqual(len(groups), 2)                                 # fastapi twice: two passes
        self.assertEqual(groups[0].split("\n")[0], "fastapi==0.1 \\")
        self.assertIn("colorama==0.4.6 \\\n    --hash=sha256:" + "d" * 64, groups[0])      # the Windows-only pin
        self.assertIn("Typing_Extensions==4.0 \\", groups[0])
        self.assertEqual(groups[1], "fastapi==0.2 \\\n    --hash=sha256:" + "b" * 64 + " \\\n    --hash=sha256:" + "c" * 64 + "\n")
        self.assertNotIn(";", "".join(groups))
        with self.assertRaises(ValueError):
            audit.requirement_blocks("fastapi>=0.1\n")                   # an unpinned line is an error, not skipped

    def test_every_pin_of_the_real_locks_is_audited_exactly_once(self):
        for name in LOCKS:
            original = audit.requirement_blocks(lock_text(name))
            groups = audit.audit_groups(lock_text(name))
            seen: list[tuple[str, str]] = []
            for group in groups:
                self.assertNotIn(";", group, name)
                names = []
                for block in audit.requirement_blocks(group):
                    m = audit.PIN.match(block[0])
                    names.append(audit.normalize(m.group("name")))
                    seen.append((names[-1], m.group("version")))
                    self.assertTrue(any("--hash=sha256:" in l for l in block[1:]), block[0])
                self.assertEqual(len(names), len(set(names)), f"{name}: a package twice in one pass")
            want = sorted((audit.normalize(audit.PIN.match(b[0]).group("name")), audit.PIN.match(b[0]).group("version"))
                          for b in original)
            self.assertEqual(sorted(seen), want, name)


class WorkflowTests(HermeticTestCase):
    def workflows(self) -> dict[str, str]:
        found = {p.name: p.read_text(encoding="utf-8") for p in sorted(WORKFLOWS.glob("*.yml"))}
        self.assertLessEqual({"ci.yml", "audit.yml"}, set(found))
        return found

    def test_every_action_is_pinned_to_a_commit(self):
        for name, text in self.workflows().items():
            uses = re.findall(r"^\s*(?:-\s*)?uses:\s*(.+)$", text, flags=re.MULTILINE)
            self.assertTrue(uses, name)
            for ref in uses:
                self.assertRegex(ref.strip(), r"^[\w.-]+/[\w./-]+@[0-9a-f]{40} # v\d+\.\d+\.\d+$", f"{name}: {ref}")

    def test_every_workflow_can_only_read_the_repository(self):
        for name, text in self.workflows().items():
            doc = yaml.safe_load(text)
            self.assertEqual(doc.get("permissions"), {"contents": "read"}, name)
            for job_name, job in doc["jobs"].items():
                self.assertNotIn("permissions", job, f"{name}: {job_name} widens the token")
            self.assertNotIn("pull_request_target", doc[True], name)      # `on:` parses as True
            self.assertEqual(text.count("actions/checkout@"), text.count("persist-credentials: false"), name)

    def test_python_installs_in_ci_are_hash_checked(self):
        for name, text in self.workflows().items():
            installs = [l.strip() for l in text.splitlines() if "pip install" in l and not l.strip().startswith("#")]
            self.assertTrue(installs, name)
            for line in installs:
                self.assertIn("--require-hashes -r reader/requirements", line, f"{name}: {line}")

    def test_the_audit_gates_and_the_test_matrix(self):
        flows = self.workflows()
        audit_flow = yaml.safe_load(flows["audit.yml"])
        runs = " ".join(str(step.get("run", "")) for step in audit_flow["jobs"]["audit"]["steps"])
        self.assertIn("audit_python_locks.py", runs)
        for name in LOCKS:
            self.assertIn(f"reader/{name}.txt", runs)
        self.assertIn("npm audit", runs)
        self.assertNotIn("continue-on-error", flows["audit.yml"])
        self.assertNotIn("|| true", flows["audit.yml"])
        self.assertLessEqual({"push", "pull_request", "schedule"}, set(audit_flow[True]))
        ci = yaml.safe_load(flows["ci.yml"])
        self.assertEqual(ci["jobs"]["test"]["strategy"]["matrix"], {"os": ["macos-latest", "windows-latest"]})
        self.assertIn("record_baselines", ci[True]["workflow_dispatch"]["inputs"])

    def test_update_pull_requests_cover_everything_that_is_pinned(self):
        doc = yaml.safe_load((REPO / ".github" / "dependabot.yml").read_text(encoding="utf-8"))
        got = {(u["package-ecosystem"], u["directory"]) for u in doc["updates"]}
        self.assertEqual(got, {("uv", "/reader"), ("npm", "/reader/frontend"), ("github-actions", "/")})
        for update in doc["updates"]:
            self.assertEqual(update["schedule"]["interval"], "weekly")


if __name__ == "__main__":
    unittest.main()
